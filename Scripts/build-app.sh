# Builds Kraal.app from the SwiftPM executable.
#
# A bare SwiftPM executable cannot be a proper macOS app: without an Info.plist
# and a bundle it has no identifier, so windows do not restore, AppKit refuses
# some services, and the Dock shows a generic icon. This script assembles a real
# .app around the already-built binary — no Xcode project required.
#
#   ./Scripts/build-app.sh            # debug, pointed at the sandbox daemon
#   ./Scripts/build-app.sh release    # release, ad-hoc signed
#
# Output: build/Kraal.app
#
# A debug bundle gets a wrapper that points `KRAAL_HERDR_SOCKET` at an isolated
# sandbox daemon. The dev loop rebuilds and relaunches this app dozens of times;
# without the override each relaunch attaches to a real herdr, and every split,
# tab and keystroke aimed at the sandbox lands in a live session instead.
#
# The default socket must be a path that only ever points at a throwaway
# container. A stale or misremembered path is worse than none: it silently
# resolves to whatever daemon happens to listen there, which is how this
# override once drove a real 12-workspace session. Point it at a path that is
# created for this purpose and nowhere else. Release builds keep the default.
#
# The same wrapper also isolates the *desktop* side of a dev launch, because a
# second copy of the app otherwise fights the first one over the pointer and the
# log file: it names the session (`KRAAL_DEV_SESSION`, derived from the socket
# path) and asks for `KRAAL_DEV_BACKGROUND=1`, which stops the app from
# activating, raising its window or stealing keyboard focus. Both are defaults —
# the caller can override either when running the wrapper by hand.

set -euo pipefail

CONFIGURATION="${1:-debug}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

APP_NAME="Kraal"
PRODUCT="KraalMac"
BUILD_DIR="$ROOT/build"
APP="$BUILD_DIR/$APP_NAME.app"
BUNDLE_ID="cool.zzj.kraal"
VERSION="0.1.0"

echo "==> Building $PRODUCT ($CONFIGURATION)"
SWIFT_FLAGS=(-c "$CONFIGURATION")
swift build --product "$PRODUCT" "${SWIFT_FLAGS[@]}"

# SwiftPM writes to .build/out for Xcode-backed toolchains and .build/debug
# otherwise; resolve whichever exists.
BIN=""
for candidate in \
    "$ROOT/.build/out/Products/$(echo "$CONFIGURATION" | awk '{print toupper(substr($0,1,1)) substr($0,2)}')/$PRODUCT" \
    "$ROOT/.build/$CONFIGURATION/$PRODUCT" \
    "$ROOT/.build/arm64-apple-macosx/$CONFIGURATION/$PRODUCT"
do
    if [ -x "$candidate" ]; then BIN="$candidate"; break; fi
done

if [ -z "$BIN" ]; then
    echo "error: built binary not found for configuration $CONFIGURATION" >&2
    exit 1
fi
echo "    binary: $BIN"

echo "==> Assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Frameworks"
if [ "$CONFIGURATION" = "debug" ]; then
    # The real binary, plus a launcher that pins the sandbox socket.
    mv_bin="$APP/Contents/MacOS/$PRODUCT"
    cp "$BIN" "$APP/Contents/MacOS/${PRODUCT}-bin"
    cat > "$mv_bin" <<LAUNCHER
#!/bin/bash
# Generated by Scripts/build-app.sh: debug builds talk to the sandbox daemon and
# stay out of the way of any other copy of the app.
#
# KRAAL_DEV_SESSION namespaces the saved window frame and the log file, so two
# sessions cannot restore onto each other's window or rotate away each other's
# log; left unset, the app derives it from the socket path.
# KRAAL_DEV_BACKGROUND=1 suppresses activation, window raise and Dock presence —
# the app still renders and is still capturable window-by-window, but it never
# takes the pointer or the keyboard.
DEFAULT_SOCKET="\${KRAAL_HERDR_SOCKET:-/tmp/kraal-mine/herdr-client.sock}"
# The session name is not derived here: the app computes it from the socket path
# (DevSession.derivedName), so there is exactly one implementation of that rule.
# A hand-set KRAAL_DEV_SESSION still wins.
export KRAAL_HERDR_SOCKET="\$DEFAULT_SOCKET"
export KRAAL_DEV_BACKGROUND="\${KRAAL_DEV_BACKGROUND:-1}"
# Machine profiles are shared by every Herdr process on the account (one
# endpoints.json, no --socket flag), so a dev session that adds a throwaway
# machine would edit the real roster. Give the child a scratch HOME instead;
# `herdr` honours \$HOME for that path and the app's own window frame and log
# stay on the real one.
DEFAULT_HERDR_HOME="\${KRAAL_HERDR_HOME:-/tmp/kraal-mine/herdr-home}"
mkdir -p "\$DEFAULT_HERDR_HOME" 2>/dev/null
export KRAAL_HERDR_HOME="\$DEFAULT_HERDR_HOME"
if [ -n "\${KRAAL_DEV_SESSION:-}" ]; then
    export KRAAL_DEV_SESSION
fi
exec "\$(dirname "\$0")/${PRODUCT}-bin" "\$@"
LAUNCHER
    chmod +x "$mv_bin"
else
    cp "$BIN" "$APP/Contents/MacOS/$PRODUCT"
fi

# SwiftPM resource bundles sit next to the binary; Ghostty's resources live in
# one of them, so they must be copied or the terminal cannot find terminfo.
for bundle in "$(dirname "$BIN")"/*.bundle; do
    [ -e "$bundle" ] || continue
    cp -R "$bundle" "$APP/Contents/Resources/"
done

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>
    <string>$APP_NAME</string>
    <key>CFBundleDisplayName</key>
    <string>$APP_NAME</string>
    <key>CFBundleExecutable</key>
    <string>$PRODUCT</string>
    <key>CFBundleIdentifier</key>
    <string>$BUNDLE_ID</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$VERSION</string>
    <key>LSMinimumSystemVersion</key>
    <string>14.0</string>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.developer-tools</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSSupportsAutomaticGraphicsSwitching</key>
    <true/>
    <key>NSHumanReadableCopyright</key>
    <string>Apache-2.0. Herdr is a trademark of Herdr, Inc.; Kraal is an independent client.</string>
</dict>
</plist>
PLIST

# Ad-hoc signature: enough for local use and for TCC to keep a stable identity.
echo "==> Signing (ad-hoc)"
codesign --force --deep --sign - "$APP" 2>/dev/null || \
    echo "    warning: ad-hoc signing failed; the app still runs unsigned"

touch "$APP"
echo "==> Done: $APP"
